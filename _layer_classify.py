LAYERS = ["一心", "三界", "五行", "九层", "象思维", "应用", "系统", "融合"]


def classify(rel):
    for pat, layer, sub, sec in RULES:
        if re.search(pat, rel):
            return layer, sub, list(sec)
    return "未归类", "未归类", []


def main():
    rows = []
    for dirpath, dirnames, filenames in os.walk(BASE):
        for fn in filenames:
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, BASE).replace("\\", "/")
            layer, sub, sec = classify(rel)
            rows.append({
                "path": "05-五行人格心理学/" + rel,
                "rel": rel,
                "name": os.path.splitext(fn)[0],
                "ext": os.path.splitext(fn)[1].lower(),
                "size": os.path.getsize(full),
                "layer": layer,
                "sub": sub,
                "sec": sec,
            })

    rows.sort(key=lambda r: (LAYERS.index(r["layer"]) if r["layer"] in LAYERS else 99, r["sub"], r["path"]))
    with open(os.path.join(ROOT, "_layer_map.json"), "w", encoding="utf-8") as f:
        json.dump(rows, f, ensure_ascii=False, indent=1)

    # 复核 TSV
    with open(os.path.join(ROOT, "_layer_map_review.tsv"), "w", encoding="utf-8") as f:
        f.write("主层\t子类\t辅层\tKB\t文件\n")
        for r in rows:
            f.write("{}\t{}\t{}\t{:.1f}\t{}\n".format(
                r["layer"], r["sub"], "/".join(r["sec"]), r["size"] / 1024, r["rel"]))

    # 控制台统计写入文件（避免 Windows 控制台编码问题）
    lines = []
    lines.append("== 三层分布 ==")
    for k, v in collections.Counter(r["layer"] for r in rows).most_common():
        lines.append(f"{k}\t{v}")
    lines.append("\n== 各层子类 ==")
    for L in LAYERS:
        sub = collections.Counter(r["sub"] for r in rows if r["layer"] == L)
        lines.append(f"\n[{L}] 共 {sum(sub.values())}")
        for k, v in sub.most_common():
            lines.append(f"  {k}\t{v}")
    lines.append("\n== 未归类 ==")
    for r in rows:
        if r["layer"] == "未归类":
            lines.append("  " + r["rel"])
    # 重名检测（wikilink 歧义）
    names = collections.Counter(r["name"] for r in rows)
    dup = {k: v for k, v in names.items() if v > 1}
    lines.append(f"\n== 重名 basename {len(dup)} 组 ==")
    for k, v in sorted(dup.items(), key=lambda x: -x[1]):
        lines.append(f"  {k}\t{v}")
        for r in rows:
            if r["name"] == k:
                lines.append(f"     {r['path']}")
    with open(os.path.join(ROOT, "_layer_stats.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("done", len(rows), "files;", len(dup), "dup names")


if __name__ == "__main__":
    main()
