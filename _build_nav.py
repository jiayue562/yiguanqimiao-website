def main():
    dest = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "_staging", "00-入口")
    if not os.path.isabs(dest):
        dest = os.path.join(ROOT, dest)
    rows = load_rows()
    counts = collections.Counter(r["layer"] for r in rows)
    os.makedirs(dest, exist_ok=True)

    files = {}
    files[HUB + ".md"] = hub_note(rows, counts)
    for L in ["一心", "三界", "五行", "九层", "象思维"]:
        files[ENTRY[L] + ".md"] = layer_note(L, rows, counts)
    files[ENTRY["应用"] + ".md"] = app_note(rows)
    files[ENTRY["系统"] + ".md"] = sys_note(rows)
    files[ENTRY["融合"] + ".md"] = fuse_note(rows)
    files[AUDIT + ".md"] = audit_note(rows, counts)
    files["导航画布·五层架构.canvas"] = canvas(rows, counts)

    # 注意：脚本要放进 05 目录，与笔记一起复制；这里先生成一份带路径占位的副本
    with open(os.path.abspath(__file__), encoding="utf-8") as f:
        script_text = f.read()

    for name, text in files.items():
        with open(os.path.join(dest, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    # 工具副本
    tools = os.path.join(os.path.dirname(dest), "工具")
    os.makedirs(tools, exist_ok=True)
    with open(os.path.join(tools, "图归位脚本.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write(script_text)

    # 校验所有 wikilink
    names = {r["name"] for r in rows} | {r["name"] + r["ext"] for r in rows if r["ext"] != ".md"}
    names.add(ATTACH)
    note_names = {os.path.splitext(n)[0] for n in files} | set(files)
    missing = collections.defaultdict(list)
    for name, text in files.items():
        for m in re.findall(r"\[\[([^\]]+)\]\]", text):
            tgt = m.split("|")[0].strip()
            if tgt in names or tgt in note_names:
                continue
            missing[name].append(tgt)
    lines = []
    lines.append("files=%d md=%d others=%d size=%s" % (
        len(rows), len([r for r in rows if r["ext"] == ".md"]),
        len([r for r in rows if r["ext"] != ".md"]), kb(sum(r["size"] for r in rows))))
    lines.append("counts=" + json.dumps(dict(counts), ensure_ascii=False))
    lines.append("generated=" + json.dumps(sorted(files.keys()), ensure_ascii=False, indent=0))
    lines.append("unresolved_links=" + json.dumps({k: v for k, v in missing.items()}, ensure_ascii=False, indent=1))
    with open(os.path.join(ROOT, "_build_check.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("built", len(files), "files ->", dest, "| unresolved:", sum(len(v) for v in missing.values()))


if __name__ == "__main__":
    main()
