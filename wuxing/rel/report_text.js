/* 主行维度词：从 mainWords 中取指定维度（xiang）的最高层位词，无则取主行最高层位词 */
function RT_dimWord(words, dim) {
  const hit = words.filter(w => w.xiang === dim);
  const pool = hit.length ? hit : words;
  if (!pool.length) return null;
  return pool.reduce((a, b) => (b.layer > a.layer ? b : a));
}
