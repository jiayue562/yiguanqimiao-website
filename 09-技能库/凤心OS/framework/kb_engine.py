    def query(self, keyword: str) -> list:
        """查询关键词相关知识和隐秘联系"""
        results = []

        # 搜索知识域
        for domain, keywords in self.DOMAINS.items():
            for kw in keywords:
                if keyword in kw or kw in keyword:
                    results.append({"type": "domain", "domain": domain, "keyword": kw})

        # 搜索隐秘联系
        for conn in self.HIDDEN_CONNECTIONS:
            conn_name, field, desc = conn
            if keyword in conn_name or keyword in field or keyword in desc:
                results.append({"type": "connection", "name": conn_name, "field": field, "description": desc})

        return results

    def get_connections_by_field(self, field: str) -> list:
        """按学科领域获取隐秘联系"""
        return [c for c in self.HIDDEN_CONNECTIONS if field in c[1]]

    def diagnose_cognitive_bias(self, description: str) -> list:
        """
        从描述中诊断可能的认知偏差
        返回匹配的偏差列表
        """
        biases = []
        patterns = [
            ("损失厌恶", "损失|亏损|害怕失去|不舍得|难以放弃", "水行恐惧"),
            ("锚定效应", "初始|起价|参照|第一印象|基准", "土行参照"),
            ("代表性启发", "典型|看起来像|肯定就是|典型特征", "木行观象"),
            ("可得性启发", "最近|常见|经常|身边|听说", "火行情绪"),
            ("框架效应", "表述|说成|听起来|感觉是", "火行表述"),
            ("后见之明", "早就知道|果然|不出所料|必然", "金行决断"),
            ("规划谬误", "计划|进度|预算|按时|预期", "木行乐观"),
            ("确定性效应", "稳定|确定|保底|肯定", "土行保守"),
        ]

        for bias_name, pattern_str, element in patterns:
            import re
            if re.search(pattern_str, description):
                biases.append({
                    "偏差": bias_name,
                    "五行关联": element,
                    "规避建议": f"激活慢思考→参考凤心OS偏差纠偏六步法"
                })

        return biases


