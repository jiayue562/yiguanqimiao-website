    def query(self, topic: str, domain: Optional[str] = None) -> Dict:
        target_domains = []
        for dname, dconfig in self.KNOWLEDGE_DOMAIN.items():
            if any(kw in topic for kw in dconfig["keywords"]):
                target_domains.append(dname)
        if not target_domains:
            target_domains = list(self.KNOWLEDGE_DOMAIN.keys())

        return {
            "topic": topic,
            "matched_domains": target_domains,
            "knowledge": {d: self.KNOWLEDGE_DOMAIN[d] for d in target_domains if d in self.KNOWLEDGE_DOMAIN},
            "connections": self._find_connections(topic),
        }

    def _find_connections(self, topic: str) -> List[Dict]:
        results = []
        for a, b, desc in self.HIDDEN_CONNECTIONS:
            if a in topic or b in topic:
                results.append({"from": a, "to": b, "description": desc})
        return results

    def cross_domain_connect(self, a: str, b: str) -> Optional[Dict]:
        for conn in self.HIDDEN_CONNECTIONS:
            if (a in conn[0] or a in conn[1]) and (b in conn[0] or b in conn[1]):
                return {"concept_a": a, "concept_b": b, "connection": conn[2]}
        return None
